#!/usr/bin/env bash
# collect_render_evidence.sh
# Proves rendered movies exist on disk with ffprobe metadata and frame extraction

set -euo pipefail

VIDEO_DIR="PROJECT_ROOT/Documents/LLM/ott/genott-phase2/genott-blender/static/videos"
EVIDENCE_DIR="PROJECT_ROOT/Documents/LLM/ott/genott-phase2/genott-blender/render_evidence"
REPORT_FILE="PROJECT_ROOT/Documents/LLM/ott/genott-phase2/genott-blender/RENDER_EVIDENCE.md"

mkdir -p "$EVIDENCE_DIR"/{60s,90s,120s,180s,other}

echo "=== RENDER EVIDENCE COLLECTION ==="
echo "Scanning: $VIDEO_DIR"

# Collect all final_movie mp4s
mapfile -t ALL_MOVIES < <(find "$VIDEO_DIR" -maxdepth 1 -name "movie_*_final_movie.mp4" -type f | sort)

TOTAL=${#ALL_MOVIES[@]}
echo "Total movies found: $TOTAL"

# Arrays for grouping
declare -a G60=() G90=() G120=() G180=() GOTHER=()

# Pass 1: classify by duration
echo "Classifying movies by duration..."
for f in "${ALL_MOVIES[@]}"; do
    dur=$(ffprobe -v quiet -show_entries format=duration -of csv=p=0 "$f" 2>/dev/null || echo "0")
    dur_int=${dur%.*}
    if   [ "$dur_int" -ge 55 ] && [ "$dur_int" -le 70 ]; then   G60+=("$f")
    elif [ "$dur_int" -ge 80 ] && [ "$dur_int" -le 100 ]; then  G90+=("$f")
    elif [ "$dur_int" -ge 110 ] && [ "$dur_int" -le 130 ]; then G120+=("$f")
    elif [ "$dur_int" -ge 170 ] && [ "$dur_int" -le 200 ]; then G180+=("$f")
    else                                                          GOTHER+=("$f")
    fi
done

echo "60s group:    ${#G60[@]}"
echo "90s group:    ${#G90[@]}"
echo "120s group:   ${#G120[@]}"
echo "180s group:   ${#G180[@]}"
echo "other group:  ${#GOTHER[@]}"

# --- Helper: extract frames from a video into a named dir ---
extract_frames() {
    local vid="$1"
    local outdir="$2"
    local label="$3"
    local base
    base=$(basename "$vid" .mp4)

    local dur
    dur=$(ffprobe -v quiet -show_entries format=duration -of csv=p=0 "$vid" 2>/dev/null || echo "1")
    local mid
    mid=$(echo "$dur / 2" | bc)
    local end
    end=$(echo "$dur - 1" | bc)
    [ "$end" -lt 1 ] && end=1

    ffmpeg -y -ss 0     -i "$vid" -frames:v 1 -q:v 2 "$outdir/${label}_first.jpg"  -loglevel quiet 2>/dev/null || true
    ffmpeg -y -ss "$mid" -i "$vid" -frames:v 1 -q:v 2 "$outdir/${label}_middle.jpg" -loglevel quiet 2>/dev/null || true
    ffmpeg -y -ss "$end" -i "$vid" -frames:v 1 -q:v 2 "$outdir/${label}_last.jpg"   -loglevel quiet 2>/dev/null || true
}

# --- Helper: probe a video ---
probe_video() {
    local f="$1"
    local size codec res dur frames
    size=$(stat -c%s "$f")
    codec=$(ffprobe -v quiet -select_streams v:0 -show_entries stream=codec_name -of csv=p=0 "$f" 2>/dev/null || echo "unknown")
    res=$(ffprobe -v quiet -select_streams v:0 -show_entries stream=width,height -of csv=p=0 "$f" 2>/dev/null | tr ',' 'x' || echo "unknown")
    dur=$(ffprobe -v quiet -show_entries format=duration -of csv=p=0 "$f" 2>/dev/null || echo "0")
    frames=$(ffprobe -v quiet -select_streams v:0 -show_entries stream=nb_frames -of csv=p=0 "$f" 2>/dev/null || echo "N/A")
    printf "| %s | %s bytes | %s | %s | %ss | %s |\n" \
        "$(basename "$f")" "$size" "$codec" "$res" "${dur%.*}" "$frames"
}

# --- Build the report ---
{
cat <<'HEADER'
# RENDER EVIDENCE REPORT
> Generated by collect_render_evidence.sh
> Physical proof of rendered movie files on disk.
> All data sourced from actual file system and ffprobe — no metadata substitution.

---

HEADER

echo "## Summary"
echo ""
echo "| Category | Count |"
echo "|----------|-------|"
echo "| 60s group | ${#G60[@]} |"
echo "| 90s group | ${#G90[@]} |"
echo "| 120s group | ${#G120[@]} |"
echo "| 180s group | ${#G180[@]} |"
echo "| Other | ${#GOTHER[@]} |"
echo "| **TOTAL** | **$TOTAL** |"
echo ""

# Total disk usage
TOTAL_DU=$(du -sh "$VIDEO_DIR" 2>/dev/null | cut -f1)
echo "**Total disk usage (video directory):** $TOTAL_DU"
echo ""
echo "---"
echo ""

# Process each group
for grp_name in "60s" "90s" "120s" "180s" "other"; do
    case "$grp_name" in
        60s)   files=("${G60[@]+"${G60[@]}"}") ;;
        90s)   files=("${G90[@]+"${G90[@]}"}") ;;
        120s)  files=("${G120[@]+"${G120[@]}"}") ;;
        180s)  files=("${G180[@]+"${G180[@]}"}") ;;
        other) files=("${GOTHER[@]+"${GOTHER[@]}"}") ;;
    esac

    count=${#files[@]}
    echo "## Duration Group: $grp_name ($count files)"
    echo ""

    if [ "$count" -eq 0 ]; then
        echo "> **VALIDATION: FAILED** — No files found in this duration group."
        echo ""
        continue
    fi

    echo "> **VALIDATION: PASSED** — $count files found."
    echo ""
    echo "| Filename | Size | Codec | Resolution | Duration | Frames |"
    echo "|----------|------|-------|------------|----------|--------|"

    for f in "${files[@]}"; do
        [ -f "$f" ] || continue
        probe_video "$f"
    done

    echo ""

    # Extract frames from first file in group
    first_file="${files[0]}"
    echo "### Frame Samples (from: $(basename "$first_file"))"
    echo ""
    extract_frames "$first_file" "$EVIDENCE_DIR/$grp_name" "${grp_name}_sample"
    echo "- First frame: \`render_evidence/${grp_name}/${grp_name}_sample_first.jpg\`"
    echo "- Middle frame: \`render_evidence/${grp_name}/${grp_name}_sample_middle.jpg\`"
    echo "- Last frame: \`render_evidence/${grp_name}/${grp_name}_sample_last.jpg\`"
    echo ""

    # ffprobe detail for first file
    echo "### ffprobe Output ($(basename "$first_file"))"
    echo ""
    echo '```'
    ffprobe -v quiet -show_format -show_streams "$first_file" 2>&1 | head -60 || echo "ffprobe failed"
    echo '```'
    echo ""
    echo "---"
    echo ""
done

echo "## All Files — Complete Inventory"
echo ""
echo "| # | Filename | Size (bytes) | Duration (s) |"
echo "|---|----------|-------------|--------------|"
idx=1
for f in "${ALL_MOVIES[@]}"; do
    [ -f "$f" ] || continue
    sz=$(stat -c%s "$f")
    dur=$(ffprobe -v quiet -show_entries format=duration -of csv=p=0 "$f" 2>/dev/null || echo "0")
    printf "| %d | %s | %s | %s |\n" "$idx" "$(basename "$f")" "$sz" "${dur%.*}"
    ((idx++))
done
echo ""

} > "$REPORT_FILE"

echo ""
echo "=== DONE ==="
echo "Report written to: $REPORT_FILE"
echo "Frames saved in:   $EVIDENCE_DIR"
echo ""
echo "Total disk usage of video directory:"
du -sh "$VIDEO_DIR"
